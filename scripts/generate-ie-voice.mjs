// Voice-over for Increased Efficiency's Remotion cut, made with ElevenLabs (the user, 2026-11-13).
//
//   node scripts/generate-ie-voice.mjs                  # Variation 7 (layout 'straight', the one that plays on All videos): missing or changed lines only
//   node scripts/generate-ie-voice.mjs --force          # all of them again
//   node scripts/generate-ie-voice.mjs --layout storyboard   # Variation 6
//   node scripts/generate-ie-voice.mjs --dry            # list what would be said and when, call nothing
//
// The lines are the cut's own (lib/remotion/efficiencyVoice.mjs: the title and each sentence, with the words retyped on the All videos page: content/storyboard/increased-efficiency-v3.json).
// Reads ELEVENLABS_API_KEY from the environment or .env.local (gitignored); the key never leaves this script and is never printed.
// Writes public/tts/ie/<layout>/<id>.mp3 (and a copy in D:\Documents\Saas\videos\public, where the MP4 render finds them) and lib/remotion/efficiencyVoiceAudio.mjs.
import fs from 'node:fs/promises';
import path from 'node:path';
import {mp3Duration} from './mp3-duration.mjs';
import {FLOW_CUT_ID, NARRATOR_CUT_ID, SOFT_CUT_ID, STORY_CUT_ID, makeRedoCut, REDO_CUT_ID, STRAIGHT_CUT_ID, STRAIGHT_LAYOUT} from '../lib/remotion/efficiencyRedo.mjs';
import {cutWordsOf} from '../lib/remotion/cutWords.mjs';
import {VOICE_ID, VOICE_MODEL, VOICE_SETTINGS, voiceFile, voiceHash, voiceLinesOf} from '../lib/remotion/efficiencyVoice.mjs';
import {VOICE_AUDIO} from '../lib/remotion/efficiencyVoiceAudio.mjs';

const ROOT = process.cwd();
const VIDEOS_PUBLIC = 'D:\\Documents\\Saas\\videos\\public';
const args = process.argv.slice(2), FORCE = args.includes('--force'), DRY = args.includes('--dry');
const layoutArg = args.includes('--layout') ? args[args.indexOf('--layout') + 1] : STRAIGHT_LAYOUT;
const LAYOUT = ['storyboard', 'flow', 'soft', 'narrator', 'story'].includes(layoutArg) ? layoutArg : STRAIGHT_LAYOUT;
const CUT_ID = LAYOUT === 'storyboard' ? REDO_CUT_ID : LAYOUT === 'flow' ? FLOW_CUT_ID : LAYOUT === 'soft' ? SOFT_CUT_ID : LAYOUT === 'narrator' ? NARRATOR_CUT_ID : LAYOUT === 'story' ? STORY_CUT_ID : STRAIGHT_CUT_ID;

async function loadKey() {
  if (process.env.ELEVENLABS_API_KEY) return process.env.ELEVENLABS_API_KEY;
  try {
    const env = await fs.readFile(path.join(ROOT, '.env.local'), 'utf8');
    for (const line of env.split('\n')) {
      const m = line.match(/^\s*ELEVENLABS_API_KEY\s*=\s*(.+?)\s*$/);
      if (m) return m[1].replace(/^["']|["']$/g, '');
    }
  } catch { /* no .env.local */ }
  return null;
}

const saved = JSON.parse(await fs.readFile(path.join(ROOT, 'content', 'storyboard', 'increased-efficiency-v3.json'), 'utf8'));
const cut = makeRedoCut(cutWordsOf(saved, CUT_ID), {layout: LAYOUT});
const lines = voiceLinesOf(cut);
console.log(`${LAYOUT}: ${lines.length} lines, the film is ${cut.seconds.toFixed(2)} s`);

const key = DRY ? null : await loadKey();
if (!DRY && !key) { console.error('Missing ELEVENLABS_API_KEY (set it in the environment or .env.local).'); process.exit(1); }

const audio = {...VOICE_AUDIO, [LAYOUT]: {}};
let spent = 0;
for (const line of lines) {
  const hash = voiceHash(line.text), rel = voiceFile(LAYOUT, line.id), file = path.join(ROOT, 'public', rel);
  const was = VOICE_AUDIO[LAYOUT]?.[line.id];
  if (DRY) { console.log(`${line.at.toFixed(2).padStart(6)} s  ${line.id.padEnd(11)} ${line.text}`); continue; }
  let ok = false;
  if (!FORCE && was?.hash === hash) { try { await fs.access(file); ok = true; } catch { /* make it */ } }
  let duration = was?.duration;
  if (ok) console.log(`skip  ${line.id}`);
  else {
    const res = await fetch(`https://api.elevenlabs.io/v1/text-to-speech/${VOICE_ID}`, {
      method: 'POST',
      headers: {'xi-api-key': key, 'content-type': 'application/json', accept: 'audio/mpeg'},
      body: JSON.stringify({text: line.text, model_id: VOICE_MODEL, voice_settings: VOICE_SETTINGS}),
    });
    if (!res.ok) { console.error(`FAIL  ${line.id}: ${res.status} ${await res.text()}`); process.exit(1); }
    const buf = Buffer.from(await res.arrayBuffer());
    duration = mp3Duration(buf);
    await fs.mkdir(path.dirname(file), {recursive: true});
    await fs.writeFile(file, buf);
    spent += line.text.length;
    console.log(`wrote ${line.id}.mp3 (${duration}s)`);
  }
  // the render project's own copy
  try {
    const copy = path.join(VIDEOS_PUBLIC, rel);
    await fs.mkdir(path.dirname(copy), {recursive: true});
    await fs.copyFile(file, copy);
  } catch (e) { console.warn(`(no copy for the render project: ${e.message})`); }
  audio[LAYOUT][line.id] = {hash, duration, text: line.text};
}
if (DRY) process.exit(0);

await fs.writeFile(path.join(ROOT, 'lib', 'remotion', 'efficiencyVoiceAudio.mjs'),
  `// Generated by scripts/generate-ie-voice.mjs: what was made for the voice-over of Increased Efficiency's cut (hash of the text + voice, seconds, the text said). Do not edit by hand.\nexport const VOICE_AUDIO = ${JSON.stringify(audio, null, 2)};\n`);

// does each line end before the next one starts, and before the film does?
console.log('\nFit:');
lines.forEach((line, i) => {
  const d = audio[LAYOUT][line.id]?.duration ?? 0, next = lines[i + 1]?.at ?? cut.seconds, room = next - line.at;
  console.log(`${line.at.toFixed(2).padStart(6)} s  ${line.id.padEnd(11)} ${d.toFixed(2)} s of ${room.toFixed(2)} s${d > room - 0.05 ? '   <-- too long' : ''}`);
});
console.log(`\nDone (${spent} characters sent to ElevenLabs).`);
