// Makes the voice-over of ANY Remotion cut with ElevenLabs, for the lines that have no audio yet (the user, 2026-11-14: "... and generate voice automatically"; 2026-11-16: "add voice over to all
// videos ... put text in between texts and generate the voice over"; written, NOT played). Node only (it writes files): the dev-only route app/api/storyboard/voice/route.js calls it when a title
// is added, retyped or deleted on the All videos page; scripts/generate-voice.mjs (`npm run gen:voice`) does the same for whole films by hand.
// For each line of the cut (lib/remotion/efficiencyVoice.mjs `voiceLinesOf`: its title, its sentences, the titles added to it): if the cut's manifest has audio for exactly that text (its hash) and
// the file is there, nothing is done; else ElevenLabs makes it, the mp3 is written under public/ (and copied to the Remotion project's public/, where the MP4 render finds it), and the manifest is
// written again with only the lines the cut has now (the audio of a title taken off is forgotten). Where a cut keeps its voice (`storeOf`):
//   a cut whose plan says `voiceKey` (every cut but Increased Efficiency's; lib/remotion/cutVoice.mjs): public/tts/cuts/<voiceKey>/<line>.mp3, lib/remotion/cutVoiceAudio.mjs
//   Increased Efficiency's cuts (by layout, as since 2026-11-13): public/tts/ie/<layout>/<line>.mp3, lib/remotion/efficiencyVoiceAudio.mjs
// One at a time (`chain`): two requests never write a manifest together. The key is read from the environment or .env.local and is never returned or printed.
import fs from 'node:fs/promises';
import path from 'node:path';
import {mp3Duration} from '../../scripts/mp3-duration.mjs';
import {VOICE_ID, VOICE_MODEL, VOICE_SETTINGS, voiceFile, voiceHash, voiceLinesOf} from './efficiencyVoice.mjs';
import {cutVoiceFile} from './cutVoice.mjs';

const VIDEOS_PUBLIC = 'D:\\Documents\\Saas\\videos\\public';
const STORES = {
  cuts: {manifest: ['lib', 'remotion', 'cutVoiceAudio.mjs'], name: 'CUT_VOICE_AUDIO',
    head: "// Generated by scripts/generate-voice.mjs (and by the All videos page, lib/remotion/cutVoiceMake.mjs): what was made for the voice-over of every Remotion cut but Increased Efficiency's ({<cut's voice key>: {<line id>: {hash of the text + voice, seconds, the text said}}}). Do not edit by hand."},
  ie: {manifest: ['lib', 'remotion', 'efficiencyVoiceAudio.mjs'], name: 'VOICE_AUDIO',
    head: "// Generated by scripts/generate-ie-voice.mjs (and by the All videos page, lib/remotion/cutVoiceMake.mjs): what was made for the voice-over of Increased Efficiency's cut (hash of the text + voice, seconds, the text said). Do not edit by hand."},
};
// Where this cut keeps its voice: its manifest, its key in it, and a line's file under public/
export const storeOf = (cut, layout) => (cut.voiceKey
  ? {...STORES.cuts, key: cut.voiceKey, file: id => cutVoiceFile(cut.voiceKey, id)}
  : {...STORES.ie, key: layout ?? 'redo', file: id => voiceFile(layout, id)});

export async function loadVoiceKey(root) {
  if (process.env.ELEVENLABS_API_KEY) return process.env.ELEVENLABS_API_KEY;
  try {
    const env = await fs.readFile(path.join(root, '.env.local'), 'utf8');
    for (const line of env.split('\n')) { const m = line.match(/^\s*ELEVENLABS_API_KEY\s*=\s*(.+?)\s*$/); if (m) return m[1].replace(/^["']|["']$/g, ''); }
  } catch { /* no .env.local */ }
  return null;
}
async function readManifest(root, store) {
  try {
    const text = await fs.readFile(path.join(root, ...store.manifest), 'utf8'), m = text.match(new RegExp(`export const ${store.name} = (\\{[\\s\\S]*\\});?\\s*$`));
    return m ? JSON.parse(m[1]) : {};
  } catch { return {}; }
}

// `force`: every line again; `log(text)`: what is done, line by line (the script's). -> {made, missing, total, lines, sent (characters sent to ElevenLabs)}
async function run({root, layout = null, cut, force = false, log = null}) {
  const store = storeOf(cut, layout), lines = voiceLinesOf(cut), manifest = await readManifest(root, store), mine = {...(manifest[store.key] ?? {})}, kept = {};
  const key = await loadVoiceKey(root), made = [], missing = [];
  let sent = 0;
  for (const line of lines) {
    const hash = voiceHash(line.text), rel = store.file(line.id), file = path.join(root, 'public', rel), was = mine[line.id];
    let ok = false;
    if (!force && was?.hash === hash) { try { await fs.access(file); ok = true; } catch { /* make it again */ } }
    if (!ok) {
      if (!key) { missing.push(line.id); continue; }
      const res = await fetch(`https://api.elevenlabs.io/v1/text-to-speech/${VOICE_ID}`, {
        method: 'POST',
        headers: {'xi-api-key': key, 'content-type': 'application/json', accept: 'audio/mpeg'},
        body: JSON.stringify({text: line.text, model_id: VOICE_MODEL, voice_settings: VOICE_SETTINGS}),
      });
      if (!res.ok) throw new Error(`ElevenLabs answered ${res.status} for “${line.text.slice(0, 40)}”`);
      const buf = Buffer.from(await res.arrayBuffer());
      await fs.mkdir(path.dirname(file), {recursive: true});
      await fs.writeFile(file, buf);
      kept[line.id] = {hash, duration: mp3Duration(buf), text: line.text};
      made.push(line.id);
      sent += line.text.length;
      log?.(`wrote ${rel} (${kept[line.id].duration} s)`);
    } else { kept[line.id] = {hash, duration: was.duration, text: line.text}; log?.(`kept  ${rel}`); }
    try { // the render project's own copy
      const copy = path.join(VIDEOS_PUBLIC, rel);
      await fs.mkdir(path.dirname(copy), {recursive: true});
      await fs.copyFile(file, copy);
    } catch { /* the render project is not here */ }
  }
  // (with no key, what was made before is kept for the lines that are still said: nothing is forgotten because a key is missing)
  for (const id of missing) if (mine[id]) kept[id] = mine[id];
  const next = {...manifest, [store.key]: kept};
  if (JSON.stringify(next) !== JSON.stringify(manifest)) await fs.writeFile(path.join(root, ...store.manifest), `${store.head}\nexport const ${store.name} = ${JSON.stringify(next, null, 2)};\n`);
  return {made, missing, total: lines.length, sent, lines: lines.map(l => ({id: l.id, text: l.text, at: l.at, ready: kept[l.id]?.hash === voiceHash(l.text), duration: kept[l.id]?.hash === voiceHash(l.text) ? kept[l.id].duration : null}))};
}

let chain = Promise.resolve();
export function makeVoice(args) {
  const job = chain.then(() => run(args), () => run(args));
  chain = job.catch(() => {});
  return job;
}
